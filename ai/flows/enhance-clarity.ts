// Enhance clarity flow to identify and add relevant examples or analogies to unclear explanations.

'use server';

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const EnhanceClarityInputSchema = z.object({
  question: z.string().describe('The question asked by the student.'),
  initialAnswer: z.string().describe('The initial answer generated by the AI.'),
});
export type EnhanceClarityInput = z.infer<typeof EnhanceClarityInputSchema>;

const EnhanceClarityOutputSchema = z.object({
  enhancedAnswer: z.string().describe('The enhanced answer with examples or analogies.'),
});
export type EnhanceClarityOutput = z.infer<typeof EnhanceClarityOutputSchema>;

export async function enhanceClarity(input: EnhanceClarityInput): Promise<EnhanceClarityOutput> {
  return enhanceClarityFlow(input);
}

const prompt = ai.definePrompt({
  name: 'enhanceClarityPrompt',
  input: {schema: EnhanceClarityInputSchema},
  output: {schema: EnhanceClarityOutputSchema},
  prompt: `You are an expert educator skilled at clarifying complex topics.

  A student asked the following question: {{{question}}}
  The initial answer was:
  {{{{initialAnswer}}}}

  Your task is to enhance the initial answer by:
  1. Identifying if the initial answer is unclear or difficult to understand.
  2. If unclear, adding relevant examples, analogies, or simpler explanations to improve clarity.
  3. If the initial answer is already clear, return it without modification.

  Ensure the enhanced answer is comprehensive and easy to understand for a student.
  Return the enhanced answer in the enhancedAnswer field. The answer should be formatted in Markdown.
`,
});

const enhanceClarityFlow = ai.defineFlow(
  {
    name: 'enhanceClarityFlow',
    inputSchema: EnhanceClarityInputSchema,
    outputSchema: EnhanceClarityOutputSchema,
  },
  async input => {
    const {output} = await prompt(input);
    return output!;
  }
);
